import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import vm from "node:vm";
const root = new URL("../", import.meta.url);
const context = {}; vm.createContext(context);
for (const file of ["js/engine.js", "js/category-planner.js"]) vm.runInContext(readFileSync(new URL(file, root), "utf8"), context);
const catalog = JSON.parse(readFileSync(new URL("data/cards.json", root), "utf8"));
const card = catalog.cards.find((card) => card.id === "ocbc-365");
const calculate = (input) => context.CardFitCategoryPlanner.calculate(card, { month: "2026-10", total: 800, ...input }, context.CardFitEngine);
assert.equal(calculate({ total: 799.99, categories: { dining: 799.99 } }).cashback, 200);
assert.equal(calculate({ categories: { dining: 500, groceries: 300 } }).cashback, 3400);
assert.equal(calculate({ month: "2026-11", categories: { dining: 500, groceries: 300 } }).cashback, 4800, "matches issuer November worked example");
assert.equal(calculate({ total: 1500, categories: { petrol: 1500 } }).cashback, 8000);
assert.equal(calculate({ total: 1600, categories: { petrol: 1600 } }).cashback, 9600);
assert.equal(calculate({ month: "2026-11", total: 3000, categories: { petrol: 3000 } }).cashback, 16000);
assert.equal(calculate({ month: "2026-11", total: 4000, categories: { petrol: 3000 } }).cashback, 16250, "revised category cap does not cap unrelated base cashback");
assert.equal(calculate({ total: 4000, categories: { petrol: 3000 } }).cashback, 16000);
assert.equal(calculate({ total: 4000, categories: { petrol: 3000 } }).capReduction, 2250);
assert.equal(calculate({ month: "2027-03", categories: { watsons: 800 } }).cashback, 2400);
assert.equal(calculate({ month: "2027-04", categories: { watsons: 800 } }).cashback, 200);
assert.equal(calculate({ categories: { utilities: 800 } }).cashback, 2400);
assert.equal(calculate({ month: "2026-11", categories: { utilities: 800 } }).cashback, 200);
assert.equal(calculate({}).cashback, 200, "unallocated total earns base only");
const advertising = calculate({ total: 0, advertisingFull: 2000, advertisingInstalment: 1000 });
assert.equal(advertising.cashback, 0);
assert.equal(advertising.advertisingCash, 2500);
assert.equal(advertising.shortfall, 80000, "separate advertising arithmetic cannot qualify lifestyle spend");
assert.throws(() => calculate({ categories: { dining: 500, groceries: 301 } }), /exceed/);
for (const total of [-1, Infinity, "broken", 100000001, {}]) assert.throws(() => calculate({ total }), /amounts/);
for (const month of ["2026-09", "2026-00", "2026-13", "invalid", "2026-1", "2100-01"]) assert.throws(() => calculate({ month }), /posting month/);
assert.throws(() => calculate({ total: 799.995 }), /two decimal places/, "fractional cents cannot round up into qualifying spend");
assert.equal(calculate({ total: 0 }).cashback, 0);
assert.equal(calculate({ total: "800.00", categories: { dining: "500.00", groceries: "300.00" } }).cashback, 3400);
assert.match(calculate({}).termsUrl, /programme\.pdf$/);
assert.match(calculate({ month: "2026-11" }).termsUrl, /wef1nov26/);
console.log("test-category-planner.mjs: dated rates, tiers, cap/base separation, advertising separation, rounding and invalid input passed");
